// Pre-bundles the forked upload parser into a single self-contained ES module
// file with NO runtime node_modules dependencies. This is committed to the
// repository at public/parser/worker.mjs so the deploy packaging step (which
// unconditionally copies public/ into the standalone artifact) always ships it,
// independent of the platform-managed next.config.js file-tracing configuration.
//
// The parser runs in an isolated child process (see lib/workspaces/parser.ts).
// Its heavy dependencies (pdfjs-dist, mammoth, mailparser) load dynamically at
// runtime and are therefore invisible to the Next.js build tracer. Inlining them
// here removes that gap entirely: the worker is standalone and needs nothing from
// node_modules on the deployed host.
//
// Regenerate with:  node scripts/build-parser-worker.mjs
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const entry = path.join(root, 'lib', 'workspaces', 'parser-process.mjs')
const outfile = path.join(root, 'public', 'parser', 'worker.mjs')

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: 'node',
  // ESM output (not CJS): pdfjs-dist's legacy build calls
  // createRequire(import.meta.url) internally. In a CJS bundle esbuild sets
  // import.meta to {}, so import.meta.url is undefined and pdfjs throws while
  // extracting text. ESM output preserves a real import.meta.url, so the
  // bundled pdfjs behaves exactly like the un-bundled source module.
  format: 'esm',
  target: 'node20',
  // Inline everything. The worker must have zero runtime module dependencies.
  external: [],
  legalComments: 'none',
  logLevel: 'info',
  // Some inlined CommonJS dependencies (e.g. mammoth) call require('fs') and
  // other Node built-ins. In ESM output esbuild routes unresolved requires
  // through a __require shim that throws "Dynamic require ... is not supported"
  // unless a real top-level `require` exists. Defining one via
  // createRequire(import.meta.url) lets those built-in requires resolve at
  // runtime (built-ins are always present); every third-party module is already
  // statically inlined, so nothing is fetched from node_modules on the host.
  banner: {
    js: [
      '/* AUTO-GENERATED by scripts/build-parser-worker.mjs. Do not edit by hand. */',
      "import { createRequire as __bvCreateRequire } from 'node:module';",
      'const require = __bvCreateRequire(import.meta.url);',
    ].join('\n'),
  },
})

console.log('Bundled parser worker ->', path.relative(root, outfile))
